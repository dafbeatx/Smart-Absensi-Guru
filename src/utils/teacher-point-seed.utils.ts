/**
 * Mengambil histori poin guru yang aman dan teruji dari LocalStorage,
 * atau me-refresh otomatis dengan baseline resmi jika cache lokal kosong/usang (< 200 item).
 */
export function getSafeInitialTeacherPointLogs(): TeacherPointLog[] {
  if (typeof window !== 'undefined' && typeof localStorage !== 'undefined') {
    try {
      const saved = localStorage.getItem('smart_absensi_teacher_point_history');
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length >= 200) {
          return parsed;
        }
      }
    } catch {}
  }
  const seeds = getInitialSeedTeacherPointLogs();
  if (typeof window !== 'undefined' && typeof localStorage !== 'undefined') {
    try {
      localStorage.setItem('smart_absensi_teacher_point_history', JSON.stringify(seeds));
    } catch {}
  }
  return seeds;
}
